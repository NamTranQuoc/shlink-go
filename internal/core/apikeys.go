// APIKeyMeta ports Rest\ApiKey\Model\ApiKeyMeta.
type APIKeyMeta struct {
	Key                 string
	Name                string
	IsNameAutoGenerated bool
	ExpirationDate      *time.Time
	RoleDefinitions     []RoleDefinition
}

// NewAPIKeyMeta ports ApiKeyMeta::fromParams(). A missing key becomes a random UUID v4. A name that PHP considers
// empty (null, "" or "0") falls back to the plain key, or to a redacted UUID when the key was generated.
func NewAPIKeyMeta(key, name *string, expirationDate *time.Time, roles []RoleDefinition) APIKeyMeta {
	resolvedKey := ""
	if key != nil {
		resolvedKey = *key
	} else {
		resolvedKey = uuid4()
	}
	m := APIKeyMeta{Key: resolvedKey, ExpirationDate: expirationDate, RoleDefinitions: roles}
	m.IsNameAutoGenerated = name == nil || *name == "" || *name == "0"
	switch {
	case !m.IsNameAutoGenerated:
		m.Name = *name
	case key == nil:
		m.Name = resolvedKey[:8] + "-****-****-****-************"
	default:
		m.Name = *key
	}
	return m
}

func uuid4() string {
	var b [16]byte
	if _, err := rand.Read(b[:]); err != nil {
		panic(err)
	}
	b[6] = b[6]&0x0f | 0x40
	b[8] = b[8]&0x3f | 0x80
	return fmt.Sprintf("%x-%x-%x-%x-%x", b[0:4], b[4:6], b[6:8], b[8:10], b[10:16])
}

// APIKeyCheckResult ports Rest\Service\ApiKeyCheckResult.
type APIKeyCheckResult struct {
	APIKey *APIKey
}

// IsValid tells if the key exists, is enabled and has not expired.
func (r APIKeyCheckResult) IsValid(now time.Time) bool {
	return r.APIKey != nil && r.APIKey.IsValid(now)
}

// APIKeyService ports Rest\Service\ApiKeyService.
type APIKeyService struct {
	Store *Store
}

func (s *Store) apiKeyColumns() string {
	return "a.id, a." + s.DB.Q("key") + ", a." + s.DB.Q("name") + ", a.expiration_date, a.enabled"
}

func (s *Store) scanAPIKey(row rowScanner) (*APIKey, error) {
	var k APIKey
	var name sql.NullString
	exp := s.nullTime()
	var enabled db.Bool
	if err := row.Scan(&k.ID, &k.Key, &name, &exp, &enabled); err != nil {
		return nil, err
	}
	k.Name = name.String
	k.ExpirationDate = exp.Ptr()
	k.Enabled = bool(enabled)
	return &k, nil
}

// findOneAPIKey ports findOneBy() on api keys, loading the roles.
func (s *Store) findOneAPIKey(ctx context.Context, q db.Querier, column string, value any) (*APIKey, error) {
	one := 1
	query := s.DB.Limit("SELECT "+s.apiKeyColumns()+" FROM api_keys a WHERE a."+s.DB.Q(column)+" = ? ORDER BY a.id",
		&one, nil)
	k, err := s.scanAPIKey(s.DB.QueryRow(ctx, q, query, value))
	if errors.Is(err, sql.ErrNoRows) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	return k, s.loadAPIKeyRoles(ctx, q, k)
}

// FindAPIKeyByPlainKey hashes a plain key and finds the API key it belongs to, with its roles.
func (s *Store) FindAPIKeyByPlainKey(ctx context.Context, key string) (*APIKey, error) {
	return s.findOneAPIKey(ctx, s.DB.DB, "key", HashAPIKey(key))
}

// lockFirstRow appends the engine's pessimistic write lock to a single-row select on api_keys (alias a).
func (s *Store) lockFirstRow(query string) string {
	one := 1
	switch s.DB.Driver {
	case db.MSSQL:
		query = strings.Replace(query, "FROM api_keys a", "FROM api_keys a WITH (UPDLOCK, ROWLOCK)", 1)
		return s.DB.Limit(query+" ORDER BY a.id", &one, nil)
	case db.SQLite:
		return s.DB.Limit(query+" ORDER BY a.id", &one, nil)
	default:
		return s.DB.Limit(query+" ORDER BY a.id", &one, nil) + " FOR UPDATE"
	}
}

// APIKeyNameExists ports ApiKeyRepository::nameExists(), locking the matching row.
func (s *Store) APIKeyNameExists(ctx context.Context, q db.Querier, name string) (bool, error) {
	var id int64
	err := s.DB.QueryRow(ctx, q, s.lockFirstRow("SELECT a.id FROM api_keys a WHERE a."+s.DB.Q("name")+" = ?"), name).Scan(&id)
	if errors.Is(err, sql.ErrNoRows) {
		return false, nil
	}
	return err == nil, err
}

// insertAPIKey ports ApiKey::fromMeta() plus its persistence. Repeated roles keep the first position and the last
// meta, like registerRole().
func (s *Store) insertAPIKey(ctx context.Context, q db.Querier, m APIKeyMeta) (*APIKey, error) {
	k := &APIKey{Key: HashAPIKey(m.Key), Name: m.Name, ExpirationDate: m.ExpirationDate, Enabled: true, Roles: []APIKeyRole{}}
	for _, def := range m.RoleDefinitions {
		meta := def.Meta
		if meta == nil {
			meta = map[string]any{}
		}
		replaced := false
		for i := range k.Roles {
			if k.Roles[i].Role == def.Role {
				k.Roles[i].Meta = meta
				replaced = true
			}
		}
		if !replaced {
			k.Roles = append(k.Roles, APIKeyRole{Role: def.Role, Meta: meta})
		}
	}
	var err error
	k.ID, err = s.DB.Insert(ctx, q, "api_keys", []string{"key", "name", "expiration_date", "enabled"},
		k.Key, k.Name, s.DB.TimeArg(k.ExpirationDate), true)
	if err != nil {
		return nil, err
	}
	for i := range k.Roles {
		r := &k.Roles[i]
		r.ID, err = s.DB.Insert(ctx, q, "api_key_roles", []string{"role_name", "meta", "api_key_id"},
			string(r.Role), EncodeMeta(r.Meta), k.ID)
		if err != nil {
			return nil, err
		}
	}
	return k, nil
}

// Create ports ApiKeyService::create(). The returned key holds the hash; the plain key is meta.Key.
func (a *APIKeyService) Create(ctx context.Context, meta APIKeyMeta) (*APIKey, error) {
	var k *APIKey
	err := a.Store.DB.InTx(ctx, func(tx *sql.Tx) error {
		unique, err := a.ensureUniqueName(ctx, tx, meta)
		if err != nil {
			return err
		}
		k, err = a.Store.insertAPIKey(ctx, tx, unique)
		return err
	})
	return k, err
}

// ensureUniqueName regenerates auto-generated names until they are unique, and rejects explicit duplicated names.
func (a *APIKeyService) ensureUniqueName(ctx context.Context, tx *sql.Tx, meta APIKeyMeta) (APIKeyMeta, error) {
	for {
		exists, err := a.Store.APIKeyNameExists(ctx, tx, meta.Name)
		if err != nil || !exists {
			return meta, err
		}
		if !meta.IsNameAutoGenerated {
			return meta, InvalidArgumentError{Message: fmt.Sprintf(`Another API key with name "%s" already exists`, meta.Name)}
		}
		meta = NewAPIKeyMeta(nil, nil, meta.ExpirationDate, meta.RoleDefinitions)
	}
}

// CreateInitial ports ApiKeyService::createInitial(): nil when other keys already exist.
func (a *APIKeyService) CreateInitial(ctx context.Context, key string) (*APIKey, error) {
	var k *APIKey
	err := a.Store.DB.InTx(ctx, func(tx *sql.Tx) error {
		var id int64
		err := a.Store.DB.QueryRow(ctx, tx, a.Store.lockFirstRow("SELECT a.id FROM api_keys a")).Scan(&id)
		if err == nil {
			// Do not create an initial API key if other keys already exist
			return nil
		}
		if !errors.Is(err, sql.ErrNoRows) {
			return err
		}
		k, err = a.Store.insertAPIKey(ctx, tx, NewAPIKeyMeta(&key, nil, nil, nil))
		return err
	})
	return k, err
}

// Check ports ApiKeyService::check().
func (a *APIKeyService) Check(ctx context.Context, key string) (APIKeyCheckResult, error) {
	k, err := a.Store.FindAPIKeyByPlainKey(ctx, key)
	return APIKeyCheckResult{APIKey: k}, err
}

// DeleteByName ports ApiKeyService::deleteByName(). Roles go through the foreign key cascade, as upstream relies on.
func (a *APIKeyService) DeleteByName(ctx context.Context, name string) error {
	res, err := a.Store.DB.Exec(ctx, a.Store.DB.DB, "DELETE FROM api_keys WHERE "+a.Store.DB.Q("name")+" = ?", name)
	if err != nil {
		return err
	}
	n, err := res.RowsAffected()
	if err != nil {
		return err
	}
	if n == 0 {
		return APIKeyNotFoundError{Name: name}
	}
	return nil
}

// DisableByName ports ApiKeyService::disableByName().
func (a *APIKeyService) DisableByName(ctx context.Context, name string) (*APIKey, error) {
	k, err := a.Store.findOneAPIKey(ctx, a.Store.DB.DB, "name", name)
	if err != nil {
		return nil, err
	}
	if k == nil {
		return nil, APIKeyNotFoundError{Name: name}
	}
	if _, err := a.Store.DB.Exec(ctx, a.Store.DB.DB, "UPDATE api_keys SET enabled = ? WHERE id = ?", false, k.ID); err != nil {
		return nil, err
	}
	k.Enabled = false
	return k, nil
}

// ListKeys ports ApiKeyService::listKeys(). Like findBy() upstream, no order is requested from the database.
func (a *APIKeyService) ListKeys(ctx context.Context, enabledOnly bool) ([]*APIKey, error) {
	query := "SELECT " + a.Store.apiKeyColumns() + " FROM api_keys a"
	var args []any
	if enabledOnly {
		query += " WHERE a.enabled = ?"
		args = append(args, true)
	}
	rows, err := a.Store.DB.Query(ctx, a.Store.DB.DB, query, args...)
	if err != nil {
		return nil, err
	}
	keys := []*APIKey{}
	for rows.Next() {
		k, err := a.Store.scanAPIKey(rows)
		if err != nil {
			rows.Close()
			return nil, err
		}
		keys = append(keys, k)
	}
	rows.Close()
	if err := rows.Err(); err != nil {
		return nil, err
	}
	return keys, a.Store.loadAPIKeyRoles(ctx, a.Store.DB.DB, keys...)
}

// RenameAPIKey ports ApiKeyService::renameApiKey().
func (a *APIKeyService) RenameAPIKey(ctx context.Context, r Renaming) (*APIKey, error) {
	k, err := a.Store.findOneAPIKey(ctx, a.Store.DB.DB, "name", r.OldName)
	if err != nil {
		return nil, err
	}
	if k == nil {
		return nil, APIKeyNotFoundError{Name: r.OldName}
	}
	if !r.NameChanged() {
		return k, nil
	}
	err = a.Store.DB.InTx(ctx, func(tx *sql.Tx) error {
		exists, err := a.Store.APIKeyNameExists(ctx, tx, r.NewName)
		if err != nil {
			return err
		}
		if exists {
			return APIKeyConflictError{Name: r.NewName}
		}
		_, err = a.Store.DB.Exec(ctx, tx, "UPDATE api_keys SET "+a.Store.DB.Q("name")+" = ? WHERE id = ?", r.NewName, k.ID)
		return err
	})
	if err != nil {
		return nil, err
	}
	k.Name = r.NewName
	return k, nil
}
