// Expected outputs were produced by the upstream image with var_export(), echo and include.
func TestVarExport(t *testing.T) {
	nested := NewArray()
	nested.Set("y", NewArray())
	value := NewArray()
	value.Set("A", 1)
	value.Set("B", nil)
	value.Set("C", true)
	value.Set("D", "it's \\ x\x00y\n")
	value.Set("E", NewList("x", nested, NewArray()))
	value.Set(5, 1.0)
	value.Set("F", 1.5e25)
	value.Set("G", 0.1)
	value.Set("H", math.Copysign(0, -1))
	value.Set("I", 1e15)
	value.Set("L", 0.00001)
	expected := "array (\n" +
		"  'A' => 1,\n" +
		"  'B' => NULL,\n" +
		"  'C' => true,\n" +
		"  'D' => 'it\\'s \\\\ x' . \"\\0\" . 'y\n',\n" +
		"  'E' => \n" +
		"  array (\n" +
		"    0 => 'x',\n" +
		"    1 => \n" +
		"    array (\n" +
		"      'y' => \n" +
		"      array (\n" +
		"      ),\n" +
		"    ),\n" +
		"    2 => \n" +
		"    array (\n" +
		"    ),\n" +
		"  ),\n" +
		"  5 => 1.0,\n" +
		"  'F' => 1.5E+25,\n" +
		"  'G' => 0.1,\n" +
		"  'H' => -0.0,\n" +
		"  'I' => 1000000000000000.0,\n" +
		"  'L' => 1.0E-5,\n" +
		")"
	if actual := VarExport(value); actual != expected {
		t.Errorf("expected\n%s\ngot\n%s", expected, actual)
	}

	parsed, err := ParseReturnFile([]byte("<?php\n/* Shlink config generated by shlink-installer */\nreturn " + expected + ";"))
	if err != nil {
		t.Fatal(err)
	}
	if actual := VarExport(parsed); actual != expected {
		t.Errorf("parsed back as\n%s", actual)
	}
}

func TestFormatFloat(t *testing.T) {
	tenth, fifth := 0.1, 0.2
	cases := []struct {
		f                    float64
		asString, serialized string
	}{
		{1e15, "1.0E+15", "1000000000000000"},
		{tenth + fifth, "0.3", "0.30000000000000004"},
		{1.0, "1", "1"},
		{1e14, "1.0E+14", "100000000000000"},
		{1.5e-5, "1.5E-5", "1.5E-5"},
		{0.0001, "0.0001", "0.0001"},
		{math.Copysign(0, -1), "-0", "-0"},
		{123456789012345678.0, "1.2345678901235E+17", "1.2345678901234568E+17"},
		{1e16, "1.0E+16", "10000000000000000"},
		{1e17, "1.0E+17", "1.0E+17"},
		{math.Inf(-1), "-INF", "-INF"},
	}
	for _, c := range cases {
		if actual := FormatFloat(c.f, 14); actual != c.asString {
			t.Errorf("%v as string: expected %s, got %s", c.f, c.asString, actual)
		}
		if actual := FormatFloat(c.f, 0); actual != c.serialized {
			t.Errorf("%v serialized: expected %s, got %s", c.f, c.serialized, actual)
		}
	}
}

func TestParseReturnFile(t *testing.T) {
	value, err := ParseReturnFile([]byte(`<?php
declare(strict_types=1);
// comment
# other comment
return [
    'S' => "tab\there \x41\101\u{1F600} \$x",
    "5" => 0x1F,
    'list' => ['a', 'b', 7 => 'c', 'd'],
    'neg' => -1_000,
    'f' => .5,
    'concat' => 'a' . 1 . "b",
    'bool' => TRUE,
];
`))
	if err != nil {
		t.Fatal(err)
	}
	expected := "array (\n" +
		"  'S' => 'tab\there AA\U0001F600 $x',\n" +
		"  5 => 31,\n" +
		"  'list' => \n" +
		"  array (\n" +
		"    0 => 'a',\n" +
		"    1 => 'b',\n" +
		"    7 => 'c',\n" +
		"    8 => 'd',\n" +
		"  ),\n" +
		"  'neg' => -1000,\n" +
		"  'f' => 0.5,\n" +
		"  'concat' => 'a1b',\n" +
		"  'bool' => true,\n" +
		")"
	if actual := VarExport(value); actual != expected {
		t.Errorf("expected\n%s\ngot\n%s", expected, actual)
	}

	for _, src := range []string{
		"<?php return getenv('FOO');",
		"<?php return ['a' => \"$foo\"];",
		"<?php $a = 1; return $a;",
		"<?php return [1, 2]",
		"return [];",
		"<?php return []; echo 1;",
	} {
		_, err := ParseReturnFile([]byte(src))
		var unsupported *UnsupportedPHPError
		if !errors.As(err, &unsupported) {
			t.Errorf("%s: expected an unsupported construct error, got %v", src, err)
		}
	}
}
