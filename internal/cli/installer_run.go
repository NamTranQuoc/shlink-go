// Paths ShlinkAssetsHandler works with, relative to the Shlink root (the working dir).
const (
	generatedConfigPath   = "config/params/generated_config.php"
	sqliteDBPath          = "data/database.sqlite"
	geoLiteDBPath         = "data/GeoLite2-City.mmdb"
	roadRunnerBinaryPath  = "bin/rr"
	configTemplatePrefix  = "<?php\n\n/* Shlink config generated by shlink-installer */\n\nreturn "
	installerExceptionDir = `Shlinkio\Shlink\Installer\Exception\`
)

var cachedConfigPaths = []string{"data/cache/app_config.php", "data/cache/fastroute_cached_routes.php"}

// importedConfig ports ImportedConfig; the zero value is ImportedConfig::notImported().
type importedConfig struct {
	importPath string
	config     *phpx.Array
}

// updateCommand ports UpdateCommand with InstallationRunner::runUpdate().
func updateCommand(io *console.IO) (int, error) {
	style := io.Style()
	imported, err := resolvePreviousConfig(style)
	if err != nil {
		return 0, err
	}
	if err := dropCachedConfigIfAny(style); err != nil {
		return 0, err
	}
	if err := importShlinkAssetsFromPath(style, imported.importPath); err != nil {
		return 0, err
	}
	initInput := map[string]any{"--skip-initialize-db": nil, "--clear-db-cache": nil}
	if fileExists(filepath.Join(imported.importPath, roadRunnerBinaryPath)) {
		initInput["--download-rr-binary"] = nil
	}
	return runInstallation(io, style, initInput, imported)
}

// runInstallation ports InstallationRunner::run().
func runInstallation(io *console.IO, style *console.SymfonyStyle, initInput map[string]any, imported importedConfig) (int, error) {
	style.Text("<info>Welcome to Shlink!!</info>", "This tool will guide you through the installation process.")
	previous := imported.config
	if previous == nil {
		previous = phpx.NewArray()
	}
	answers, err := generateConfigInteractively(style, previous)
	if err != nil {
		return 0, err
	}
	if err := writeConfigFile(generatedConfigPath, normalizeAndKeepEnvVarKeys(answers)); err != nil {
		return 0, err
	}
	style.Text("<info>Custom configuration properly generated!</info>")
	style.NewLine(1)

	init, err := io.App.Find("init")
	if err != nil {
		return 0, err
	}
	code, err := init.Run(io.With(console.NewArrayInput(initInput), style))
	if err != nil {
		return 0, err
	}
	if code != console.Success {
		return console.Failure, nil
	}
	style.Success("Installation complete!")
	return console.Success, nil
}

// generateConfigInteractively ports ConfigGenerator::generateConfigInteractively(): options already in the previous
// config are not asked again, and every group title is rendered once, before its first asked option.
func generateConfigInteractively(io *console.SymfonyStyle, previous *phpx.Array) (*phpx.Array, error) {
	answers := phpx.Merge(phpx.NewArray(), previous)
	for _, group := range configOptionGroups {
		titleRendered := false
		for _, envVar := range group.options {
			option := configOptions[envVar]
			ask, err := option.shouldAsk(answers)
			if err != nil {
				return nil, err
			}
			if !ask {
				continue
			}
			if !titleRendered {
				titleRendered = true
				io.Title(group.title)
			}
			value, err := option.ask(io, answers)
			if err != nil {
				return nil, err
			}
			answers.Set(envVar, value)
		}
	}
	return answers, nil
}

// normalizeAndKeepEnvVarKeys ports Utils::normalizeAndKeepEnvVarKeys(): only keys made of uppercase or numeric
// segments separated by "_" are kept, arrays are imploded, and legacy schema and driver values are migrated.
func normalizeAndKeepEnvVarKeys(answers *phpx.Array) *phpx.Array {
	filtered := answers.Filter(func(key any) bool {
		for _, part := range strings.Split(phpx.ToString(key), "_") {
			if !isUpper(part) && !config.IsNumericValue(config.StringValue(part)) {
				return false
			}
		}
		return true
	})
	legacyDrivers := map[string]string{"pdo_pgsql": "postgres", "pdo_sqlite": "sqlite", "pdo_sqlsrv": "mssql",
		"pdo_mysql": "mysql"}
	for _, it := range filtered.Items() {
		switch v := it.Value.(type) {
		case *phpx.Array:
			filtered.Set(it.Key, phpx.Implode(",", v))
			continue
		}
		if it.Key == "IS_HTTPS_ENABLED" {
			if _, isBool := it.Value.(bool); !isBool {
				filtered.Set(it.Key, it.Value == "https")
			}
			continue
		}
		if s, isString := it.Value.(string); isString && it.Key == "DB_DRIVER" && legacyDrivers[s] != "" {
			filtered.Set(it.Key, legacyDrivers[s])
		}
	}
	return filtered
}

// isUpper ports ctype_upper().
func isUpper(s string) bool {
	if s == "" {
		return false
	}
	for i := 0; i < len(s); i++ {
		if s[i] < 'A' || s[i] > 'Z' {
			return false
		}
	}
	return true
}

// writeConfigFile ports ConfigWriter::toFile() with webimpress/safe-writer's FileWriter::writeFile(): the content is
// written to a temporary file in the same directory, which then replaces the target.
func writeConfigFile(file string, answers *phpx.Array) error {
	content := configTemplatePrefix + phpx.VarExport(answers) + ";\n"
	dir := filepath.Dir(file)
	safeWriterError := func(class, message string, line int) error {
		return &console.PHPError{Class: `Webimpress\SafeWriter\Exception\` + class, Message: message,
			File: class + ".php", Line: line}
	}
	var tmp *os.File
	var err error
	for range 100 {
		name := filepath.Join(dir, "wsw"+strconv.FormatUint(rand.Uint64()%(1<<40), 36))
		tmp, err = os.OpenFile(name, os.O_CREATE|os.O_EXCL|os.O_WRONLY, 0o666)
		if !errors.Is(err, os.ErrExist) {
			break
		}
	}
	if err != nil {
		return safeWriterError("RuntimeException", fmt.Sprintf(`Could not create temporary file in directory "%s"`, dir), 28)
	}
	if _, err := io.WriteString(tmp, content); err != nil {
		_ = tmp.Close()
		_ = os.Remove(tmp.Name())
		return safeWriterError("WriteContentException", fmt.Sprintf(`Could not write content to the file "%s"`, tmp.Name()), 28)
	}
	_ = tmp.Close()
	if err := os.Rename(tmp.Name(), file); err != nil {
		_ = os.Remove(tmp.Name())
		return safeWriterError("RenameException", fmt.Sprintf(`Could not move file "%s" to location "%s": either the `+
			`source file is not readable, or the destination is not writable`, tmp.Name(), file), 28)
	}
	return nil
}

func fileExists(path string) bool {
	_, err := os.Stat(path)
	return err == nil
}

// dropCachedConfigIfAny ports ShlinkAssetsHandler::dropCachedConfigIfAny().
func dropCachedConfigIfAny(io *console.SymfonyStyle) error {
	for _, file := range cachedConfigPaths {
		if !fileExists(file) {
			continue
		}
		if err := os.RemoveAll(file); err != nil {
			io.Error(fmt.Sprintf(`Could not delete cached config! You will have to manually delete the "%s" file.`, file))
			return filesystemError(fmt.Sprintf(`Failed to remove file "%s": %s.`, file, err))
		}
	}
	return nil
}

func filesystemError(message string) error {
	return &console.PHPError{Class: `Symfony\Component\Filesystem\Exception\IOException`, Message: message,
		File: "Filesystem.php", Line: 0}
}

// resolvePreviousConfig ports ShlinkAssetsHandler::resolvePreviousConfig().
func resolvePreviousConfig(io *console.SymfonyStyle) (importedConfig, error) {
	importConfig, err := io.Confirm("Do you want to import configuration from previous installation? (You will still "+
		"be asked for any new config option that did not exist in previous shlink versions)", true)
	if err != nil || !importConfig {
		return importedConfig{}, err
	}
	var installationPath, configFile string
	for {
		answer, err := io.Ask("Previous shlink installation path from which to import config", nil,
			validateRequired("previous installation path"))
		if err != nil {
			return importedConfig{}, err
		}
		installationPath = phpx.ToString(answer)
		configFile = installationPath + "/" + generatedConfigPath
		if fileExists(configFile) {
			break
		}
		retry, err := io.Confirm("Provided path does not seem to be a valid shlink root path. Do you want to try "+
			"another path?", true)
		if err != nil {
			return importedConfig{}, err
		}
		if !retry {
			return importedConfig{}, nil
		}
	}
	previous, err := config.IncludeConfigFile(configFile)
	if err != nil {
		return importedConfig{}, err
	}
	return importedConfig{importPath: installationPath, config: previous}, nil
}

// importShlinkAssetsFromPath ports ShlinkAssetsHandler::importShlinkAssetsFromPath().
func importShlinkAssetsFromPath(io *console.SymfonyStyle, path string) error {
	if source := path + "/" + sqliteDBPath; fileExists(source) {
		if err := copyFile(source, sqliteDBPath); err != nil {
			io.Error("It was not possible to import the SQLite database")
			return err
		}
	}
	if source := path + "/" + geoLiteDBPath; fileExists(source) {
		if err := copyFile(source, geoLiteDBPath); err != nil {
			io.Note("It was not possible to import GeoLite db. Skipping and letting regular update take care of it.")
		}
	}
	return nil
}

// copyFile ports Symfony's Filesystem::copy() without overwriting newer files: the target is only replaced when the
// origin was modified later, and it keeps the origin's modification time and executable bits.
func copyFile(origin, target string) error {
	failed := func() error { return filesystemError(fmt.Sprintf(`Failed to copy "%s" to "%s".`, origin, target)) }
	originInfo, err := os.Stat(origin)
	if err != nil {
		return filesystemError(fmt.Sprintf(`Failed to copy "%s" because file does not exist.`, origin))
	}
	if targetInfo, err := os.Stat(target); err == nil && targetInfo.Mode().IsRegular() &&
		!originInfo.ModTime().After(targetInfo.ModTime()) {
		return nil
	}
	if err := os.MkdirAll(filepath.Dir(target), 0o777); err != nil {
		return failed()
	}
	src, err := os.Open(origin)
	if err != nil {
		return failed()
	}
	defer src.Close()
	dst, err := os.OpenFile(target, os.O_CREATE|os.O_TRUNC|os.O_WRONLY, 0o666)
	if err != nil {
		return failed()
	}
	if _, err := io.Copy(dst, src); err != nil {
		_ = dst.Close()
		return failed()
	}
	if err := dst.Close(); err != nil {
		return failed()
	}
	if targetInfo, err := os.Stat(target); err == nil {
		_ = os.Chmod(target, targetInfo.Mode().Perm()|originInfo.Mode().Perm()&0o111)
	}
	_ = os.Chtimes(target, originInfo.ModTime(), originInfo.ModTime())
	return nil
}

// setOptionCommand ports SetOptionCommand.
func setOptionCommand(io *console.IO) (int, error) {
	style := io.Style()
	cwd, _ := os.Getwd()
	path := cwd + "/" + generatedConfigPath
	if !fileExists(path) {
		return 0, &console.PHPError{Class: installerExceptionDir + "InvalidShlinkPathException",
			Message: `This command needs to be run inside a Shlink installation directory where the "install" command ` +
				`has been run first`, File: "InvalidShlinkPathException.php", Line: 13}
	}
	titles := make([]string, len(setOptionChoices))
	for i, c := range setOptionChoices {
		titles[i] = c.title
	}
	title, err := style.Choice("What config option do you want to change", titles, nil)
	if err != nil {
		return 0, err
	}
	if title == "" {
		// No option was chosen (non-interactive input)
		return 0, setOptionNullChoiceFatal()
	}
	var option *configOption
	for _, c := range setOptionChoices {
		if c.title == title {
			option = configOptions[c.envVar]
		}
	}
	answers, err := config.IncludeConfigFile(path)
	if err != nil {
		return 0, err
	}
	value, err := option.ask(style, answers)
	if err != nil {
		return 0, err
	}
	answers.Set(option.envVar, value)
	if err := writeConfigFile(path, answers); err != nil {
		return 0, err
	}
	if err := dropCachedConfigIfAny(style); err != nil {
		return 0, err
	}
	style.Success("Configuration properly updated")
	return console.Success, nil
}

