// targetContainer returns the container SHLINK_CLI runs the CLI in ("docker exec -i <container> shlink").
func targetContainer(t *testing.T) string {
	t.Helper()
	cli := h.LoadConfig().CLI
	if len(cli) < 4 || cli[0] != "docker" || cli[1] != "exec" {
		t.Skip("SHLINK_CLI does not run the CLI through docker exec")
	}
	return cli[len(cli)-2]
}

func dockerExec(t *testing.T, container, stdin string, command ...string) h.CLIResult {
	t.Helper()
	cmd := exec.Command("docker", append([]string{"exec", "-i", container}, command...)...)
	cmd.Stdin = strings.NewReader(stdin)
	var out, errOut bytes.Buffer
	cmd.Stdout, cmd.Stderr = &out, &errOut
	code := 0
	if err := cmd.Run(); err != nil {
		exitErr, ok := err.(*exec.ExitError)
		if !ok {
			t.Fatalf("docker exec %v: %v", command, err)
		}
		code = exitErr.ExitCode()
	}
	return h.CLIResult{Stdout: out.String(), Stderr: errOut.String(), ExitCode: code}
}
