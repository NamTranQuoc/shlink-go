// installerStep is one step of an installer scenario: a shlink-installer command, a Shlink command, or reading a file
// of the target, whose outcome is compared with the golden <scenario>-<step name>.
type installerStep struct {
	name      string
	installer bool
	args      []string
	inputs    []string
	// file, when set, is read instead of running a command
	file string
}

const generatedConfig = "/etc/shlink/config/params/generated_config.php"

// TestInstallerConfigGoldens runs the installer commands that generate config/params/generated_config.php, and checks
// the file and the env vars Shlink promotes from it.
